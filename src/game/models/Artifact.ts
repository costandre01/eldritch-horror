/*
 * ============================================================
 * ARTIFACT TYPE
 * ============================================================
 *
 * Main type printed on the Artifact card.
 *
 * All Core Artifacts are Items.
 */

export type ArtifactType =
    | "item";

/*
 * ============================================================
 * ARTIFACT TRAITS
 * ============================================================
 *
 * Additional traits printed on the Artifact card.
 */

export type ArtifactTrait =
    | "weapon"
    | "tome"
    | "magical"
    | "teamwork";

/*
 * ============================================================
 * ARTIFACT
 * ============================================================
 *
 * Represents one physical Artifact card in the live game.
 */

export interface Artifact {
    /*
     * ========================================================
     * IDENTITY
     * ========================================================
     */

    id: string;

    definitionId: string;

    name: string;

    /*
     * ========================================================
     * CARD TYPE
     * ========================================================
     */

    type: ArtifactType;

    /*
     * ========================================================
     * TRAITS
     * ========================================================
     */

    traits: ArtifactTrait[];

    /*
     * ========================================================
     * RULES TEXT
     * ========================================================
     */

    description: string;

    /*
     * ========================================================
     * IMAGE
     * ========================================================
     */

    image: string;
}